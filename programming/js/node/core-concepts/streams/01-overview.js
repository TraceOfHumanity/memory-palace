//               ПЕРЕТВОРЮЄТЬСЯ Й З'ЯВЛЯЄТЬСЯ НА ВИХОДІ (стиснення
//               gzip, шифрування) — 05-duplex-and-transform.js


// ==========================================================================
// 4. НАЙПРОСТІШИЙ ПРИКЛАД: ЧИТАННЯ ФАЙЛУ ЯК STREAM ЗАМІСТЬ readFile()
// ==========================================================================

const fs = require("fs");
const fsPromises = require("fs/promises");
const os = require("os");
const path = require("path");
const demoFilePath = path.join(os.tmpdir(), "streams-overview-demo.txt");

async function main() {
  // СТВОРЮЄМО ФАЙЛ ІЗ КІЛЬКОМА РЯДКАМИ ДЛЯ ДЕМОНСТРАЦІЇ:
  await fsPromises.writeFile(demoFilePath, "рядок 1\nрядок 2\nрядок 3\n".repeat(1000));

  await new Promise((resolve, reject) => {
    const readStream = fs.createReadStream(demoFilePath, { encoding: "utf-8" });

    let totalBytes = 0;
    let chunkCount = 0;

    readStream.on("data", (chunk) => {
      // ДАНІ НАДХОДЯТЬ ЧАСТИНАМИ (chunks) — розмір ОДНОГО chunk'а
      // ЗАЛЕЖИТЬ ВІД highWaterMark (детально 02-readable-streams.js),
      // А НЕ ВІД ЛОГІЧНИХ "рядків" файлу:
      totalBytes += chunk.length;
      chunkCount++;
    });

    readStream.on("end", () => {
      console.log(`Прочитано ${totalBytes} байтів у ${chunkCount} chunks`);
      // ЦЕ ГОЛОВНА ВІДМІННІСТЬ ВІД fs.readFile(): дані НЕ ЗБЕРІГАЮТЬСЯ
      // ВСІ ОДРАЗУ В ОДНІЙ ЗМІННІЙ — вони ОБРОБЛЯЮТЬСЯ "НА ЛЬОТУ",
      // ЧАСТИНАМИ, І ПОТІМ "ЗАБУВАЮТЬСЯ" (якщо самому НЕ зберегти)
      resolve();
    });

    readStream.on("error", reject); // ⚠️ ЗАВЖДИ обробляй error — розділ 6
  });


  // ========================================================================
  // 5. STREAM VS "ЗАВАНТАЖИТИ ВСЕ Й ОБРОБИТИ" — ПОРІВНЯННЯ ПАМ'ЯТІ
  // ========================================================================

  // ФАЙЛ У 100 MB ЧЕРЕЗ readFile(): ~100 MB У ПАМ'ЯТІ ОДНОЧАСНО
  // (ВЕСЬ файл ЦІЛИКОМ, ЯК ОДИН Buffer/рядок).
  //
  // ФАЙЛ У 100 MB ЧЕРЕЗ STREAM: У ПАМ'ЯТІ В БУДЬ-ЯКИЙ МОМЕНТ ЧАСУ
  // ЛИШЕ ОДИН chunk (типово ДЕСЯТКИ КІЛОБАЙТ, ЗАЛЕЖНО ВІД
  // highWaterMark) — НЕЗАЛЕЖНО ВІД ТОГО, НАСКІЛЬКИ ВЕЛИКИЙ ФАЙЛ
  // ЦІЛОМУ: 100 MB, 1 GB чи 100 GB — СПОЖИВАННЯ ПАМ'ЯТІ ЗАЛИШАЄТЬСЯ
  // ПРИБЛИЗНО ОДНАКОВИМ.


  // ========================================================================
  // 6. ПОМИЛКИ У STREAMS — ЧОМУ "error" НЕ МОЖНА ІГНОРУВАТИ
  // ========================================================================

  // НА ВІДМІНУ ВІД async/await (детально common/asynchronous/asynchronous.js,
  // розділ 12), ДЕ НЕОБРОБЛЕНА ПОМИЛКА СТАЄ "unhandled rejection",
  // У STREAMS НЕОБРОБЛЕНА ПОДІЯ "error" ПРИЗВОДИТЬ ДО ТОГО, ЩО
  // NODE.JS КИДАЄ ЇЇ ЯК ЗВИЧАЙНИЙ EXCEPTION І, ЗА ЗАМОВЧУВАННЯМ,
  // ЗАВЕРШУЄ ВЕСЬ ПРОЦЕС (детально сама подія — Node.js EventEmitter
  // МАЄ СПЕЦІАЛЬНУ ПОВЕДІНКУ САМЕ ДЛЯ "error"):

  await new Promise((resolve) => {
    const brokenStream = fs.createReadStream(path.join(os.tmpdir(), "no-such-file.txt"));
    brokenStream.on("error", (err) => {
      console.log("Очікувана, ОБРОБЛЕНА помилка:", err.code); // "ENOENT"
      resolve();
    });
    // БЕЗ .on("error", ...) ТУТ — ПРОЦЕС ЗАВЕРШИВСЯ Б ІЗ НЕОБРОБЛЕНИМ
    // ВИКЛЮЧЕННЯМ, НАВІТЬ ЯКЩО РЕШТА КОДУ "НІБИ" НЕ МАЄ ДО ЦЬОГО СТОСУНКУ
  });


  // ========================================================================
  // ПРИБИРАННЯ
  // ========================================================================
  await fsPromises.rm(demoFilePath, { force: true });
}

main().catch((err) => console.error("Помилка в демонстрації:", err));


