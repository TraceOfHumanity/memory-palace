// - Streams вирішують проблему пам'яті: дані обробляються ЧАСТИНАМИ
//   (chunks) "на льоту", БЕЗ потреби тримати ВЕСЬ обсяг у пам'яті
//   одночасно — незалежно від того, наскільки великий файл/потік даних
// - КОЖЕН Stream — ЦЕ EventEmitter: робота відбувається через
//   .on("data"/"end"/"error"/...), а не через return-значення
// - ЧОТИРИ типи: Readable (джерело), Writable (приймач), Duplex
//   (обидва напрямки незалежно), Transform (вхід перетворюється у вихід)
// - розмір ОДНОГО chunk'а НЕ відповідає "логічним" одиницям даних
//   (рядкам файлу тощо) — це просто шматок байтів певного розміру
//   (highWaterMark), і ЦЕ ТРЕБА враховувати при обробці (детально
//   пастка з "розрізаними" рядками — 04-piping-and-backpressure.js)
// - подію "error" НІКОЛИ НЕ можна залишати без обробника — на
//   відміну від async/await, необроблена "error" завершує ВЕСЬ процес